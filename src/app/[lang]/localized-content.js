const pagePaths = {
  home: "",
  brasileiro: "/campeonatos/brasileiro",
  champions: "/campeonatos/champions",
}

export function getPageContent(lang, page) {
  return translations[lang]?.[page]
}

export function getLocalizedMetadata(lang, page) {
  const content = getPageContent(lang, page)
  const path = pagePaths[page]
  const localizedUrl = (locale) =>
    `https://www.futlance.com${locale === "pt" ? "" : `/${locale}`}${path}`
  const url = localizedUrl(lang)

  return {
    title: content.title,
    description: content.description,
    keywords: content.keywords,
    alternates: {
      canonical: url,
      languages: Object.fromEntries(
        Object.entries(languageTags).map(([locale, tag]) => [tag, localizedUrl(locale)])
      ),
    },
    openGraph: {
      title: content.title,
      description: content.description,
      url,
      siteName: "Futlance",
      locale: languageTags[lang].replace("-", "_"),
      alternateLocale: Object.entries(languageTags)
        .filter(([locale]) => locale !== lang)
        .map(([, tag]) => tag.replace("-", "_")),
      type: "website",
    },
  }
}
